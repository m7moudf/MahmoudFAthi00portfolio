const languageToggle = document.querySelector("#language-toggle");
const pageDescription = document.querySelector('meta[name="description"]');

function setLanguage(language) {
  const languagePack = translations[language];
  if (!languagePack) return;

  document.documentElement.lang = language;
  document.documentElement.dir = language === "ar" ? "rtl" : "ltr";
  document.title = languagePack.pageTitle;

  if (pageDescription) {
    pageDescription.content = languagePack.pageDescription;
  }

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const translation = languagePack[element.dataset.i18n];
    if (translation) element.textContent = translation;
  });

  document.querySelectorAll("[data-i18n-aria]").forEach((element) => {
    const translation = languagePack[element.dataset.i18nAria];
    if (translation) element.setAttribute("aria-label", translation);
  });

  if (languageToggle) {
    const nextLanguage = language === "ar" ? "en" : "ar";
    languageToggle.textContent = nextLanguage === "ar" ? "العربية" : "English";
    languageToggle.setAttribute("aria-label", nextLanguage === "ar" ? "Switch language to Arabic" : "التبديل إلى اللغة الإنجليزية");
    languageToggle.setAttribute("aria-pressed", String(language === "ar"));
  }
}

if (languageToggle) {
  languageToggle.addEventListener("click", () => {
    setLanguage(document.documentElement.lang === "ar" ? "en" : "ar");
  });
}

const menuToggle = document.querySelector(".menu-toggle");
const siteNavigation = document.querySelector("#site-navigation");

if (menuToggle && siteNavigation) {
  menuToggle.addEventListener("click", () => {
    const isExpanded = menuToggle.getAttribute("aria-expanded") === "true";
    menuToggle.setAttribute("aria-expanded", String(!isExpanded));
    siteNavigation.classList.toggle("is-open", !isExpanded);
  });

  siteNavigation.addEventListener("click", (event) => {
    if (event.target instanceof HTMLAnchorElement) {
      menuToggle.setAttribute("aria-expanded", "false");
      siteNavigation.classList.remove("is-open");
    }
  });
}

